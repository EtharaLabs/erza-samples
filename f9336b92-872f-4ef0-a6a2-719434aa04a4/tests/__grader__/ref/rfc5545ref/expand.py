"""Recurrence set computation: BYSETPOS, nonexistent times, COUNT and UNTIL."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime

from .localtime import Floating, TimeForm, form_of, instant, localize, localize_start, wall_clock
from .model import MAX_YEAR, MIN_YEAR, HorizonError, Rule
from .bounds import never
from .periods import cycle_length, interval_walls, next_live
from .plan import Plan, compile_plan
from .validate import validate


class CapFormError(TypeError):
    """``until_cap`` is naive for a non-floating DTSTART, or aware for a floating one."""

    def __init__(self) -> None:
        super().__init__("until_cap must be naive exactly when DTSTART is floating")


@dataclass(frozen=True, slots=True)
class _Context:
    plan: Plan
    form: TimeForm
    wall: datetime
    start: datetime


def _context(rule: Rule, dtstart: datetime) -> _Context:
    validate(rule, dtstart)
    if not MIN_YEAR <= dtstart.year <= MAX_YEAR:
        raise HorizonError(dtstart.year)
    form = form_of(dtstart)
    wall = wall_clock(dtstart)
    return _Context(compile_plan(rule, wall), form, wall, localize_start(wall, form))


def _select(walls: list[datetime], ctx: _Context) -> list[datetime]:
    """Instances of one interval: drop nonexistent times, then apply BYSETPOS.

    Nonexistent local times are not part of the recurrence set (lines
    2382-2386), so they are removed before BYSETPOS indexes "the set of
    recurrence instances" of the interval (lines 2364-2370). DTSTART's own
    wall time is exempt: it always denotes an instant (lines 1894-1899) and
    is "the first instance in the recurrence set" (lines 6819-6820).
    BYSETPOS n counts from 1 at the start and -n from the end (lines
    2377-2380) over the interval's set in wall-clock order; positions
    outside the set select nothing. The result is resolved, in wall-clock
    order (which is instant order except for a normalized DTSTART).
    """
    pool: list[datetime] = []
    for wall in walls:
        value = ctx.start if wall == ctx.wall else localize(wall, ctx.form)
        if value is not None:
            pool.append(value)
    positions = ctx.plan.rule.bysetpos
    if not positions:
        return pool
    size = len(pool)
    chosen = {n - 1 if n > 0 else size + n for n in positions if -size <= n <= size}
    return [pool[index] for index in sorted(chosen)]


def synchronized(rule: Rule, dtstart: datetime) -> bool:
    """Whether DTSTART is itself an instance generated by the rule.

    Section 3.8.5.3 (lines 6820-6823): "The DTSTART property value SHOULD be
    synchronized with the recurrence rule ... The recurrence set generated
    with a DTSTART property value not synchronized with the recurrence rule
    is undefined." DTSTART is synchronized when its wall time survives every
    BYxxx part, including BYSETPOS, in the interval that contains it.
    COUNT and UNTIL play no part.
    """
    ctx = _context(rule, dtstart)
    if never(ctx.plan):
        return False
    walls = interval_walls(ctx.plan, 0) or []
    return any(value is ctx.start for value in _select(walls, ctx))


def _bound(rule: Rule, ctx: _Context, until_cap: datetime | None) -> datetime | None:
    """The inclusive upper bound (lines 2255-2258), as an absolute instant.

    UNTIL and ``until_cap`` are compared with instances by instant, not by
    wall time; with a floating DTSTART both are naive wall times.
    """
    floating = isinstance(ctx.form, Floating)
    bounds: list[datetime] = []
    if isinstance(rule.until, datetime):
        bounds.append(instant(rule.until))
    if until_cap is not None:
        if (until_cap.tzinfo is None) != floating:
            raise CapFormError
        bounds.append(instant(until_cap))
    return min(bounds) if bounds else None


def expand(rule: Rule, dtstart: datetime, *, limit: int, until_cap: datetime | None = None) -> list[datetime]:
    """The first ``limit`` instances of ``rule`` from ``dtstart``, ascending.

    Intervals are visited in order (FREQ and INTERVAL, lines 2415-2417);
    each interval's candidates are produced by the BYxxx parts in
    ``plan``/``periods`` and reduced by ``_select``. Instances before DTSTART
    are not part of the set (DTSTART "defines the first instance",
    lines 6819-6820); DTSTART is emitted when the rule generates it, i.e.
    when :func:`synchronized` holds. Then COUNT and UNTIL apply (line 2419):
    COUNT counts emitted instances only (lines 2272-2274, 2385-2386) and
    UNTIL is inclusive (lines 2255-2258). Instances are deduplicated by
    instant ("Duplicate instances are ignored", lines 6830-6840).

    Zoned results carry the DTSTART ZoneInfo with ``fold=0``; UTC results
    carry ``datetime.timezone.utc``; floating results are naive.
    """
    ctx = _context(rule, dtstart)
    bound = _bound(rule, ctx, until_cap)
    target = limit if rule.count is None else min(limit, rule.count)
    found: list[datetime] = []
    if target <= 0 or never(ctx.plan):
        return found
    start_instant = instant(ctx.start)
    last: datetime | None = None
    cycle = cycle_length(rule.freq, rule.interval)
    streak = 0
    k = 0
    while True:
        live = next_live(ctx.plan, k)
        if live is None:
            return found
        streak += live - k
        k = live
        walls = interval_walls(ctx.plan, k)
        if walls is None:
            return found
        streak = 0 if walls else streak + 1
        if streak > cycle:
            return found
        for value in _select(walls, ctx):
            moment = instant(value)
            if moment < start_instant or (last is not None and moment <= last):
                continue
            if bound is not None and moment > bound:
                return found
            found.append(value)
            last = moment
            if len(found) == target:
                return found
        k += 1
