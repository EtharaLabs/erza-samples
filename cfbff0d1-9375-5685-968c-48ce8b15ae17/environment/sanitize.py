"""Turn the upstream regress tree at 0328ab6 into the tree shipped to the agent.

Usage: python sanitize.py <extracted regress tree>
Removes the PikeVM backend, the regress-tool and gen-unicode workspace members, CI files, and the
commented-out duplicate-named-group backreference TODO. Every edit asserts its anchor.
"""
import re
import shutil
import sys
import pathlib

root = pathlib.Path(sys.argv[1])


def edit(rel, before, after, count=1):
    path = root / rel
    text = path.read_text()
    if text.count(before) != count:
        raise SystemExit(f"{rel}: expected {count} anchor(s), found {text.count(before)}: {before[:60]!r}")
    path.write_text(text.replace(before, after))


for rel in ("src/pikevm.rs", "regress-tool", "gen-unicode", ".github", ".gitignore"):
    path = root / rel
    if path.is_dir():
        shutil.rmtree(path)
    else:
        path.unlink()

edit("Cargo.toml", '[workspace]\nmembers = ["regress-tool", "gen-unicode", "."]\ndefault-members = ["regress-tool", "."]\n', "[workspace]\n")
edit("Cargo.toml", 'default = ["backend-pikevm", "std"]', 'default = ["std"]')
edit("Cargo.toml", "# Enables the PikeVM backend.\nbackend-pikevm = []\n\n", "")

edit("src/lib.rs", '\n#[cfg(feature = "backend-pikevm")]\nmod pikevm;\n', "\n")
edit("src/api.rs", '#[cfg(feature = "backend-pikevm")]\nuse crate::pikevm;\n', "")
edit("src/api.rs", "// Currently there is only the classical backtracking, and PikeVM.\n", "// Currently there is only the classical backtracking.\n")
edit(
    "src/api.rs",
    '    /// A Executor using the PikeVM executor.\n    #[cfg(feature = "backend-pikevm")]\n'
    "    pub type PikeVMExecutor<'r, 't> = super::pikevm::PikeVMExecutor<'r, indexing::Utf8Input<'t>>;\n\n",
    "",
)

common = "tests/common/mod.rs"
edit(common, "            // We don't test the PikeVM backend with UTF16 or UCS2.\n", "")
edit(
    common,
    '            #[cfg(feature = "backend-pikevm")]\n            (true, Backend::PikeVM) => {\n'
    "                rbe::find::<rbe::PikeVMExecutor>(&self.re, input, start).collect()\n            }\n\n"
    '            #[cfg(feature = "backend-pikevm")]\n            (false, Backend::PikeVM) => {\n'
    "                rbe::find::<rbe::PikeVMExecutor>(&self.re, input, start).collect()\n            }\n\n",
    "",
)
edit(common, '    #[cfg(feature = "backend-pikevm")]\n    PikeVM,\n', "")
text = (root / common).read_text()
# Every remaining `#[cfg(feature = "backend-pikevm")] { ... }` block in the config helpers.
pattern = re.compile(r'\n    #\[cfg\(feature = "backend-pikevm"\)\]\n    \{\n(?:        .*\n|\n)*?    \}\n')
text, n = pattern.subn("\n", text)
if n != 2:
    raise SystemExit(f"{common}: expected 2 PikeVM config blocks, removed {n}")
(root / common).write_text(text)

# The commented-out block in test_duplicate_named_groups_tc that describes the missing backreference support.
tests = (root / "tests/tests.rs").read_text()
start = tests.index("    // TODO: Backreferences with duplicate named groups require additional work")
end_anchor = '    //assert!(tc.compile(r"(?:(?<a>x)|(?<a>y))\\k<a>")'
end = tests.index(end_anchor, start)
end = tests.index("\n", tests.index(";", end)) + 1
(root / "tests/tests.rs").write_text(tests[:start] + tests[end:])

edit("src/lib.rs", ' There is also the "PikeVM" pseudo-toy backend which is mainly used for testing and verification.', "")
readme = (root / "README.md").read_text()
start = readme.index("### Fun Tools")
end = readme.index("\n## ", start)
(root / "README.md").write_text(readme[:start] + readme[end + 1 :])

leftover = [
    str(p.relative_to(root))
    for p in root.rglob("*")
    if p.is_file()
    and re.search(r"(?i)pikevm|regress-tool|gen-unicode", p.read_text(errors="ignore").replace("autogenerated from gen-unicode", ""))
]
if leftover:
    raise SystemExit(f"references left: {leftover}")
print("sanitized")
